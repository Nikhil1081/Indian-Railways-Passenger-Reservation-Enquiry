let currentLanguage = localStorage.getItem("rail_lang") || "en";

function setAppLanguage(lang) {
  if (!I18N_TRANSLATIONS[lang]) lang = "en";
  currentLanguage = lang;
  localStorage.setItem("rail_lang", lang);

  const dict = I18N_TRANSLATIONS[lang];
  const enDict = I18N_TRANSLATIONS["en"];

  // Update text for all elements with data-i18n attribute
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dict && dict[key]) {
      el.textContent = dict[key];
    } else if (enDict && enDict[key]) {
      el.textContent = enDict[key];
    }
  });

  // Update placeholder for elements with data-i18n-placeholder attribute
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (dict && dict[key]) {
      el.setAttribute("placeholder", dict[key]);
    } else if (enDict && enDict[key]) {
      el.setAttribute("placeholder", enDict[key]);
    }
  });

  // Set language selector dropdown value
  const langSelect = document.getElementById("language-select");
  if (langSelect && langSelect.value !== lang) {
    langSelect.value = lang;
  }

  // Handle RTL for Urdu
  if (lang === "ur") {
    document.body.classList.add("rtl-mode");
  } else {
    document.body.classList.remove("rtl-mode");
  }
}

function t(key, fallback = "") {
  const dict = I18N_TRANSLATIONS[currentLanguage] || I18N_TRANSLATIONS["en"];
  return (dict && dict[key]) || (I18N_TRANSLATIONS["en"] && I18N_TRANSLATIONS["en"][key]) || fallback || key;
}

window.I18N = {
  setLanguage: setAppLanguage,
  t: t,
  getCurrent: () => currentLanguage,
  translations: I18N_TRANSLATIONS
};
